/** Compressed representation of unit face curvature for GPU transfer */
class MappedUnitShapeCurve final
{
                uint32_t polyCurvePlanes; /**< Compressed horizontal and vertical curvature */
                uint32_t polyCurveRotation; /**< Compressed rotation start point */
};

/** Full detail unit shape with curved faces */
class MappedUnitShape final
{
                alignas(16) MappedUnitShapeCurve top; /**< Top face curvature */
                alignas(16) MappedUnitShapeCurve down; /**< Bottom face curvature */
                alignas(16) MappedUnitShapeCurve left; /**< Left face curvature */
                alignas(16) MappedUnitShapeCurve right; /**< Right face curvature */
                alignas(16) MappedUnitShapeCurve front; /**< Front face curvature */
                alignas(16) MappedUnitShapeCurve back; /**< Back face curvature */

                uint16_t polyCurveLTop; /**< Left face top edge */
                uint16_t polyCurveRTop; /**< Right face top edge */
                uint16_t polyCurveLDown; /**< Left face bottom edge */
                uint16_t polyCurveRDown; /**< Right face bottom edge */
                uint16_t polyCurveLRight; /**< Left face right edge */
                uint16_t polyCurveRLeft; /**< Right face left edge */
                uint16_t polyCurveLLeft; /**< Left face left edge */
                uint16_t polyCurveRRight; /**< Right face right edge */

                uint16_t width; /**< Unit width */
                uint16_t height; /**< Unit height */
                uint16_t depth; /**< Unit depth */
};

/** Medium detail unit shape with simplified curves */
class MappedUnitShapeMedium final
{
                alignas(8) uint32_t polyCurveRotation; /**< Shared rotation for all faces */
                uint16_t polyCurveHorizontal; /**< Shared horizontal curvature */
                uint16_t polyCurveVertical; /**< Shared vertical curvature */
                uint16_t width; /**< Unit width */
                uint16_t height; /**< Unit height */
                uint16_t depth; /**< Unit depth */
};

/** Low detail unit shape with no curves, basic cubic form */
class MappedUnitShapeLow final
{
                uint16_t width; /**< Unit width */
                uint16_t height; /**< Unit height */
                uint16_t depth; /**< Unit depth */
                uint8_t  visibleFaces; /**< Bitmask of visible faces: top(1), bottom(2),
                            left(4), right(8), front(16), back(32) */
};

/** Culled unit shape with only top face visible */
class MappedUnitShapeCulledTop final
{
                alignas(16) MappedUnitShapeCurve top; /**< Top face curvature */
                uint16_t width; /**< Unit width */
                uint16_t height; /**< Unit height */
                uint16_t depth; /**< Unit depth */
};

/** Culled unit shape with only side faces visible */
class MappedUnitShapeCulledSides final
{
                alignas(16) MappedUnitShapeCurve left; /**< Left face curvature */
                alignas(16) MappedUnitShapeCurve right; /**< Right face curvature */
                alignas(16) MappedUnitShapeCurve front; /**< Front face curvature */
                alignas(16) MappedUnitShapeCurve back; /**< Back face curvature */
                uint16_t width; /**< Unit width */
                uint16_t height; /**< Unit height */
                uint16_t depth; /**< Unit depth */
};

/** Culled unit shape with only bottom face visible */
class MappedUnitShapeCulledBottom final
{
                alignas(16) MappedUnitShapeCurve down; /**< Bottom face curvature */
                uint16_t width; /**< Unit width */
                uint16_t height; /**< Unit height */
                uint16_t depth; /**< Unit depth */
};

/** Level of detail for unit rendering */
enum class UnitLOD : uint8_t
{
        Full   = 0, /**< Full polygonal deformation with detailed curves */
        Medium = 1, /**< Simplified curves with reduced precision */
        Low    = 2, /**< Basic cubic shape without curves */
        Culled = 3 /**< Face culling optimization for hidden faces */
};

/** Compressed unit shape data (16 bytes total) */
struct CompressedUnitShape final
{
                uint32_t packedRotations; /**< 6 faces × 5 bits = 30 bits for rotation data */
                uint32_t packedCurvatures; /**< 6 faces × 5 bits = 30 bits for curvature planes */
                uint32_t packedEdges; /**< 6 edges × 4 bits = 24 bits for edge curves */
                uint32_t packedDimensions; /**< width (10 bits) | height (10 bits) | depth (10 bits)
                                              | padding (2 bits) */
};

/** Unit generated by GPU post-processing compute shaders */
struct PostUnit final
{
        public:
                enum class FlagBit
                {
                        SOLID   = 0x01,
                        VISIBLE = 0x02,
                        LIQUID  = 0x04
                };
                uint32_t
                    packedFlags; /**< lodLevel (8 bits) | flags (8 bits) | reserved (16 bits) */
                uint32_t            _padding; /**< Alignment padding for std430 */
                CompressedUnitShape shape; /**< Compressed shape data (16 bytes) */
                uint32_t _padding2[2]; /**< Additional padding to align to 32 bytes for std430 */
};

